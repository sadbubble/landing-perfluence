/**
 * Делит строку на части, чтобы выделить числа жирным:
 * «до 200 Мбит/с» → [«до », 200, « Мбит/с»].
 *
 * Так строка читается с одного взгляда — глаз цепляется за цифру, а не
 * за предлог. В макете заказчика сделано именно так. Шаблон рисует числа
 * в <b>, остальное — в <span>.
 */
export function splitNumbers(text: string): { text: string; bold: boolean }[] {
  return text.split(/(\d+)/).map((part) => ({ text: part, bold: /^\d+$/.test(part) }));
}
